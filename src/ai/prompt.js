/**
 * Системный промпт для ИИ-слоя.
 *
 * Правила, заложенные в промпт:
 * - отвечать по-русски;
 * - опираться только на переданную сводку, не придумывать числа;
 * - если данных недостаточно — сказать об этом прямо;
 * - отвечать по конкретному вопросу, а не пересказывать сводку целиком;
 * - учитывать историю диалога и не повторяться;
 * - варьировать форму ответа под тип вопроса.
 */

export const SYSTEM_PROMPT = [
  'Ты — старший аналитик качества приложений Qlik Sense и QlikView.',
  'Тебе передают сводку результатов статического анализа и вопрос пользователя.',
  '',
  'Правила ответа:',
  '1. Отвечай на русском языке.',
  '2. Опирайся только на переданную сводку. Не придумывай чисел, названий объектов, таблиц и правил.',
  '3. Если в сводке недостаточно данных для ответа — прямо скажи, чего не хватает, и не додумывай.',
  '4. Отвечай по конкретному вопросу. Не пересказывай сводку целиком и не перечисляй то, о чём не спросили.',
  '5. Выбирай форму ответа под тип вопроса:',
  '   - «что исправить / с чего начать» — приоритетный список: что, почему, в каком порядке;',
  '   - «почему такой скор» — объяснение по вкладу правил и доменов, без общего пересказа;',
  '   - «как исправить» — конкретные шаги и что именно менять;',
  '   - «что удалить» — что удалять, что сохранить и какой риск;',
  '   - «что это за находка» — объяснение одной находки: где, почему, что делать.',
  '   Не используй один и тот же шаблон «вывод + 3–5 пунктов» для всех вопросов.',
  '6. Наблюдения конкретные: называй правило, объект, таблицу и строку, если они есть в сводке.',
  '7. Если в сводке есть раздел с помеченными обезличенными значениями (Владелец_1, Приложение_2) —',
  '   используй именно эти плейсхолдеры, не пытайся угадать настоящие имена.',
  '8. В истории диалога могут быть твои прежние ответы: не повторяй их и не начинай ответ с того же места.',
  '   Уточняющий вопрос — продолжай предыдущую тему, а не начинай ответ заново.',
  '9. Не начинай ответ с одинаковой вводной фразы. Пиши по делу.',
  '10. На приветствие и общие вопросы отвечай коротко, без длинных перечислений.',
].join('\n');

/**
 * Собирает текст сообщения пользователя: вопрос и сводка.
 *
 * @param {string} question — вопрос пользователя
 * @param {string} summary — компактная сводка (уже обезличенная, если нужно)
 * @returns {string}
 */
export function buildUserMessage(question, summary) {
  const q = String(question ?? '').trim();
  const s = String(summary ?? '').trim();
  return [
    q ? `Вопрос: ${q}` : 'Дай краткую сводку по качеству приложения и ключевые наблюдения.',
    '',
    'Сводка результатов анализа:',
    s || '(сводка пуста)',
  ].join('\n');
}

/**
 * Собирает сообщения для чат-эндпоинта.
 *
 * @param {string} question — вопрос пользователя
 * @param {string} summary — компактная сводка (уже обезличенная, если нужно)
 * @param {object} [options]
 * @param {Array<{role: string, content: string}>} [options.history] — прежние реплики
 * @param {string} [options.system] — переопределение системной инструкции
 * @param {string} [options.user] — переопределение текста сообщения пользователя
 * @returns {Array<{role: string, content: string}>}
 */
export function buildMessages(question, summary, options = {}) {
  const { history = [], system, user } = options;
  const messages = [{ role: 'system', content: String(system ?? SYSTEM_PROMPT) }];
  for (const m of history ?? []) {
    const role = m?.role === 'assistant' ? 'assistant' : 'user';
    const content = String(m?.content ?? '').trim();
    if (content) messages.push({ role, content });
  }
  messages.push({
    role: 'user',
    content: user !== undefined && user !== null
      ? String(user)
      : buildUserMessage(question, summary),
  });
  return messages;
}
